/**
 * Publisher gate: structural rules every agent patch must satisfy before the
 * control zone turns it into a branch. Deterministic, no model involved.
 */
import { diffStats } from './diff.js';
import { matchesAny } from './glob.js';

/**
 * @param {ReturnType<import('./diff.js').parseUnifiedDiff>} files
 * @param {{paths: {queueOwned: string[], holdout: string[]}, limits: {maxChangedLines: number}}} config
 * @param {{allowHoldout?: boolean, carriedLines?: number}} [options] `allowHoldout` is set for the specify
 *   step only; `carriedLines` counts lines that ship in the same change but come from another step.
 * @returns {{ok: boolean, violations: Array<{rule: string, path?: string, detail: string}>}}
 */
export function checkPatch(files, config, options = {}) {
  const violations = [];
  if (files.length === 0) {
    violations.push({ rule: 'empty_patch', detail: 'The step produced no change.' });
  }
  for (const file of files) {
    const path = file.path || file.oldPath;
    if (file.unsafePath) {
      violations.push({ rule: 'unsafe_path', path, detail: 'Path is absolute, escapes the tree, or could not be parsed.' });
      continue;
    }
    if (file.symlink) violations.push({ rule: 'symlink', path, detail: 'Symbolic links are not accepted from agents.' });
    if (file.submodule) violations.push({ rule: 'submodule', path, detail: 'Submodules are not accepted from agents.' });
    if (file.binary) violations.push({ rule: 'binary', path, detail: 'Binary content is not accepted from agents.' });
    if (file.modeChanged) violations.push({ rule: 'mode_change', path, detail: 'File mode changes are not accepted from agents.' });
    for (const candidate of new Set([file.path, file.oldPath])) {
      if (matchesAny(candidate, config.paths.queueOwned)) {
        violations.push({ rule: 'queue_owned', path: candidate, detail: 'This file is regenerated by the merge queue; agents must not edit it.' });
      }
      if (!options.allowHoldout && matchesAny(candidate, config.paths.holdout)) {
        violations.push({ rule: 'holdout', path: candidate, detail: 'Holdout scenarios are written by the specify step only.' });
      }
    }
  }
  const carried = options.carriedLines ?? 0;
  const changedLines = diffStats(files).changedLines + carried;
  if (changedLines > config.limits.maxChangedLines) {
    const share = carried > 0 ? ` (${carried} of them in hidden scenarios)` : '';
    violations.push({
      rule: 'too_large',
      detail: `${changedLines} changed lines${share} exceed the limit of ${config.limits.maxChangedLines}.`,
    });
  }
  return { ok: violations.length === 0, violations };
}
